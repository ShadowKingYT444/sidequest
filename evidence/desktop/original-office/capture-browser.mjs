import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
import {readFile,writeFile} from 'node:fs/promises';
import path from 'node:path';
const evidence=path.dirname(fileURLToPath(import.meta.url));
const root=path.resolve(evidence,'../../..');
const require=createRequire(path.join(root,'desktop/package.json'));
const {chromium,expect}=require('@playwright/test');
const browser=await chromium.launch({executablePath:'/usr/bin/chromium',args:['--enable-unsafe-swiftshader']});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[],consoleErrors=[],failures=[],resources=[];
page.on('console',m=>{if(m.type()==='error')consoleErrors.push(m.text());});
page.on('pageerror',e=>errors.push(e.message));
page.on('requestfailed',r=>failures.push({url:new URL(r.url()).pathname,error:r.failure()?.errorText}));
page.on('response',r=>{if(new URL(r.url()).pathname.startsWith('/office/'))resources.push({path:new URL(r.url()).pathname,status:r.status()});});
await page.emulateMedia({reducedMotion:'reduce'});
await page.goto('http://127.0.0.1:5173/');
await expect(page.locator('.office-canvas canvas')).toBeVisible({timeout:120000});
await expect(page.getByRole('region',{name:'Office asset pending'})).toHaveCount(0);
await page.waitForLoadState('networkidle',{timeout:120000});
await expect(page.locator('.app-footer')).toHaveAttribute('data-actor-status','ready',{timeout:120000});
await page.screenshot({path:path.join(evidence,'original-office-overview.png')});
const nav=page.getByRole('combobox',{name:'Office navigation'});
await expect(nav.locator('optgroup[label="Computer files"] option')).toHaveCount(24);
await nav.selectOption('parent_019');
await expect(page.getByTestId('diff-editor')).toHaveCount(1,{timeout:30000});
await page.waitForTimeout(4000);
await page.screenshot({path:path.join(evidence,'original-office-monitor.png')});
await page.getByRole('button',{name:'Expand',exact:true}).click();
await expect(page.getByRole('dialog',{name:'Computer work viewer'})).toBeVisible();
await page.screenshot({path:path.join(evidence,'original-office-expanded.png')});
await page.keyboard.press('Escape');
await expect(page.getByTestId('diff-editor')).toHaveCount(0);
const allBindings=JSON.parse(await readFile(path.join(root,'desktop/public/office/bindings.json'),'utf8'));
const result={testedAt:new Date().toISOString(),baseCommit:'1e4b7440cb526f09203a7351af1abe8b69dd922f',viewport:{width:1440,height:1000},stationCount:allBindings.stations.length,stagedActorCount:26,actorsAreArtworkOnly:true,overviewRendered:true,measuredMonitorSelected:'parent_019',actualGitDiffMounted:true,expandedViewerVisible:true,escapeReturnedToOverview:true,pageErrors:errors,consoleErrors,requestFailures:failures,assetResponses:resources};
await writeFile(path.join(evidence,'browser-validation.json'),JSON.stringify(result,null,2)+'\n');
await browser.close();
expect(errors).toEqual([]);expect(consoleErrors).toEqual([]);expect(failures).toEqual([]);expect(resources.every(r=>r.status===200)).toBe(true);
console.log(JSON.stringify({...result,assetResponses:resources.length}));
